// Generates unity/Assets/Sigilbound/Core/HeroArt.Generated.cs from the web game's art tables:
// art.js LOOKS[*].kit, and three3d.mjs BODY (builds, borrowed parts, proportions) and FACE.
// Run from the repo root whenever those tables change:  node unity/Tests~/fixtures/make-hero-art.cjs
"use strict";
const fs = require("fs");
const path = require("path");
const root = path.resolve(__dirname, "../../..");
const art = fs.readFileSync(path.join(root, "public/game/art.js"), "utf8");
const t3 = fs.readFileSync(path.join(root, "game3d/three3d.mjs"), "utf8");
function grab(src, name) {
  const i = src.indexOf(`const ${name} = {`);
  if (i < 0) throw new Error("missing " + name);
  let depth = 0;
  const j = src.indexOf("{", i);
  for (let k = j; k < src.length; k++) {
    if (src[k] === "{") depth++;
    else if (src[k] === "}") { depth--; if (!depth) return eval("(" + src.slice(j, k + 1) + ")"); }
  }
  return null;
}
const LOOKS = grab(art, "LOOKS"), BODY = grab(t3, "BODY"), FACE = grab(t3, "FACE");
const lit = (v) => typeof v === "string" ? JSON.stringify(v) : typeof v === "boolean" ? String(v) : typeof v === "number" ? `${v}d` : "null";
const out = [];
out.push("// GENERATED by unity/Tests~/fixtures/make-hero-art.cjs from public/game/art.js (LOOKS kit) and");
out.push("// game3d/three3d.mjs (BODY, FACE). Do not edit by hand; regenerate instead.");
out.push("using System.Collections.Generic;");
out.push("");
out.push("namespace Sigilbound.Core");
out.push("{");
out.push("    public static partial class HeroArt");
out.push("    {");
out.push("        // LOOKS[id].kit: 3D-only kit options (cape, robe, shield, helm style, hair piece...).");
out.push("        public static readonly Dictionary<string, Dictionary<string, object>> KitTable = new Dictionary<string, Dictionary<string, object>>");
out.push("        {");
for (const [id, L] of Object.entries(LOOKS)) {
  const kv = Object.entries(L.kit || {}).map(([k, v]) => `[${JSON.stringify(k)}] = ${lit(v)}`).join(", ");
  out.push(`            [${JSON.stringify(id)}] = new Dictionary<string, object> { ${kv} },`);
}
out.push("        };");
out.push("");
out.push("        // BODY[id]: borrowed parts, hidden materials, shave/bald, proportions.");
out.push("        public static readonly Dictionary<string, BodySpec> BodyTable = new Dictionary<string, BodySpec>");
out.push("        {");
for (const [id, B] of Object.entries(BODY)) {
  const parts = Object.entries(B.parts || {}).map(([k, v]) => `[${JSON.stringify(k)}] = ${JSON.stringify(v)}`).join(", ");
  const f = [];
  f.push(`Parts = new Dictionary<string, string> { ${parts} }`);
  f.push(`Hide = new string[] { ${(B.hide || []).map((x) => JSON.stringify(x)).join(", ")} }`);
  if (B.shave) f.push("Shave = true");
  if (B.bald) f.push("Bald = true");
  if (B.h) f.push(`H = ${B.h}d`);
  if (B.head) f.push(`Head = ${B.head}d`);
  if (B.bulk) f.push(`Bulk = new[] { ${B.bulk.map((x) => x + "d").join(", ")} }`);
  if (B.arms) f.push(`Arms = ${B.arms}d`);
  if (B.legs) f.push(`Legs = ${B.legs}d`);
  if (B.sh) f.push(`Sh = ${B.sh}d`);
  out.push(`            [${JSON.stringify(id)}] = new BodySpec { ${f.join(", ")} },`);
}
out.push("        };");
out.push("");
out.push("        // FACE[id]: brow angle (deg; + stern, - kind), mouth shape and iris colour.");
out.push("        public static readonly Dictionary<string, FaceSpec> FaceTable = new Dictionary<string, FaceSpec>");
out.push("        {");
for (const [id, F] of Object.entries(FACE)) out.push(`            [${JSON.stringify(id)}] = new FaceSpec { Brow = ${F.brow}d, Mouth = ${JSON.stringify(F.mouth)}, Iris = ${JSON.stringify(F.iris)} },`);
out.push("        };");
out.push("    }");
out.push("}");
const dest = path.join(root, "unity/Assets/Sigilbound/Core/HeroArt.Generated.cs");
fs.writeFileSync(dest, out.join("\n") + "\n");
console.log("wrote", path.relative(root, dest), Object.keys(LOOKS).length, "kits,", Object.keys(BODY).length, "bodies,", Object.keys(FACE).length, "faces");
